defmodule AshGreenmask.GeneratorTest do
  use ExUnit.Case, async: true

  alias AshGreenmask.Generator
  alias AshGreenmask.Test.Support

  test "builds the greenmask document from declarations" do
    assert {:ok, %{transform: [table]}, residuals} = Generator.build([Support.Domain])

    # Only resources carrying declarations appear.
    assert table.schema == "public"
    assert table.name == "people"

    by_column = Map.new(table.transformers, &{&1.params["column"], &1})

    assert {"email", "RandomEmail", %{}} = transformer(by_column, "email")
    assert {"phone", "Masking", %{"type" => :tel}} = transformer(by_column, "phone")

    assert {"full_name", "Hash", %{"function" => "sha3-512"}} =
             transformer(by_column, "full_name")

    assert {"secret_note", "Cmd", %{"program" => "note-shaper", "driver" => :json}} =
             transformer(by_column, "secret_note")

    # Residuals: one line per keep, because verbatim.
    assert residuals == [
             "#{inspect(Support.Person)}: :organization_id — tenant key; a copy without it cannot be scoped"
           ]
  end

  test "a sensitive attribute with no position refuses generation, naming resource and attribute" do
    assert {:error, reasons} = Generator.build([Support.UncoveredDomain])
    assert [reason] = reasons
    assert reason =~ "#{inspect(Support.Uncovered)}: :email is sensitive"
    assert reason =~ "neither `transform` nor `keep`"
  end

  test "rendering is deterministic and carries the header, residuals and cmd warning" do
    assert {:ok, document, residuals} = Generator.build([Support.Domain])
    first = document |> Generator.render(residuals) |> IO.iodata_to_binary()
    second = document |> Generator.render(residuals) |> IO.iodata_to_binary()
    assert first == second

    assert first =~ "generated by `mix ash_greenmask.gen.config`"
    assert first =~ "Residuals — what passes through unchanged, and why:"
    assert first =~ ":organization_id — tenant key; a copy without it cannot be scoped"
    assert first =~ "cmd transformers in use:"
    assert first =~ "executes an arbitrary command at dump time"
    assert first =~ "GREENMASK_GLOBAL_SALT"

    assert first =~ ~s(name: "Masking")
    assert first =~ ~s(column: "phone")
  end

  defp transformer(by_column, column) do
    t = Map.fetch!(by_column, column)
    {column, t.name, Map.delete(t.params, "column")}
  end
end
